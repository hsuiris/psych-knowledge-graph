// Applied / practical psychology guides.
//
// Positioned differently from the concept graph: the graph is for people who
// want to explore the *theory* of the whole field; these guides are for people
// who want to *understand others and apply psychology to real life* — managers,
// parents, anyone working on themselves.
//
// Each guide stays grounded in real, named psychology (no invented studies) and
// cross-links into the concept graph via `relatedConcepts` (ids in graph.json).

export interface GuidePrinciple {
  /** the named principle / theory */
  name: string;
  /** plain-language explanation, paragraphs separated by \n\n */
  body: string;
}

export interface GuideScenario {
  /** a concrete, everyday situation */
  situation: string;
  /** what's actually going on, psychologically */
  insight: string;
  /** what to try instead */
  action: string;
}

export type GuideGroup = "role" | "theme";

export interface Guide {
  id: string;
  /** who / what this is for, e.g. 「給主管」 */
  audience: string;
  title: string;
  /** one-line hook */
  tagline: string;
  group: GuideGroup;
  /** accent colour (hex) */
  accent: string;
  emoji: string;
  /** lead overview, paragraphs separated by \n\n */
  intro: string;
  /** the few ideas that do most of the work */
  principles: GuidePrinciple[];
  /** situation → insight → action */
  scenarios: GuideScenario[];
  /** things people get wrong */
  pitfalls?: string[];
  /** questions to ask yourself */
  reflection?: string[];
  /** ids of concepts in the graph this guide draws on */
  relatedConcepts: string[];
}

